"""v1.9 revision analyses (offline; no API calls).

  S1  Holm adjustment over the two matched recovery-control tests (order swap, constraint)
  S2  Draw-position diagnostics for the conditional i.i.d. assumption:
      per-position accuracy / tie rate / A-share, Cochran's Q across positions,
      pairwise agreement between positions (exchangeability check)
  S3  Forced-choice Direct accuracy by subset (for Table 9)
  S4  Binary-correctness vs deployed modal aggregation on the test split
  S5  Blinded human-audit kit for the 37 unanimous K-persistent errors
      (+37 matched controls as distractors): annotator sheets + hidden key
Writes revision_numbers_v19.md and ../human_audit_v19/*.
"""
from __future__ import annotations
import csv, json, os, random
from collections import Counter
from itertools import combinations
import numpy as np
from statsmodels.stats.contingency_tables import cochrans_q

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "revision_numbers_v19.md")
L = []
def P(s=""): L.append(s)
def jl(n): return [json.loads(l) for l in open(os.path.join(HERE, n), encoding="utf-8") if l.strip()]
def votes_of(s):
    return [v.strip(" '\"") for v in s.strip("[]").split(",")] if isinstance(s, str) else s

SUB = {"full_natural.jsonl": "Natural", "full_neighbor.jsonl": "Neighbor", "full_gptinst.jsonl": "GPTInst",
       "full_gptout.jsonl": "GPTOut", "full_manual.jsonl": "Manual"}
rec = json.load(open(os.path.join(HERE, "records.json"), encoding="utf-8"))
byid, T = {}, []
for ds, items in rec["datasets"].items():
    for i, x in enumerate(items):
        iid = f"{SUB[ds]}_{i:03d}"; x = dict(x); x["iid"] = iid; x["subset"] = SUB[ds]
        byid[iid] = x
        if x["split"] == "test": T.append(x)
N = len(T)
P("# v1.9 revision numbers (generated by analyze_v19_revisions.py)")

# ---------- S1 ----------
P("\n## S1. Holm adjustment, matched recovery-control tests")
raw = {"order swap (K=5)": 0.0490, "constraint-focused (T=0)": 0.0225}
# recompute exactly from the pair tables in revision_numbers_v18.md: (b, c) discordant pairs
from scipy.stats import binomtest
pairs = {"order swap (K=5)": (13, 4), "constraint-focused (T=0)": (11, 2)}
raw = {k: binomtest(b, b + c, 0.5).pvalue for k, (b, c) in pairs.items()}
order = sorted(raw, key=raw.get); m = len(order); adj = {}; run = 0
for j, k in enumerate(order):
    run = max(run, min(1.0, (m - j) * raw[k])); adj[k] = run
for k in pairs:
    P(f"- {k}: discordant {pairs[k][0]}/{pairs[k][1]}, exact McNemar p = {raw[k]:.4f}, Holm-adjusted p = {adj[k]:.4f}")

# ---------- S2 ----------
P("\n## S2. Draw-position diagnostics (conditional i.i.d. check)")
def position_block(name, rows):
    V = [r[0] for r in rows]; G = [r[1] for r in rows]; n = len(V); K = len(V[0])
    corr = np.array([[1 if v[j] == g else 0 for j in range(K)] for v, g in zip(V, G)])
    tie = np.array([[1 if v[j] == "tie" else 0 for j in range(K)] for v in V])
    isA = np.array([[1 if v[j] == "A" else 0 for j in range(K)] for v in V])
    P(f"\n### {name} (N={n}, K={K})")
    P("- Accuracy by position: " + ", ".join(f"{corr[:, j].mean():.3f}" for j in range(K)))
    P("- Tie rate by position: " + ", ".join(f"{tie[:, j].mean():.3f}" for j in range(K)))
    P("- Share of A by position: " + ", ".join(f"{isA[:, j].mean():.3f}" for j in range(K)))
    for lab, M in (("correctness", corr), ("A-choice", isA)):
        if M.std() == 0:
            P(f"- Cochran's Q ({lab}): constant"); continue
        q = cochrans_q(M)
        P(f"- Cochran's Q ({lab}): Q = {q.statistic:.2f}, df = {K-1}, p = {q.pvalue:.3f}")
    ag = [np.mean([v[a] == v[b] for v in V]) for a, b in combinations(range(K), 2)]
    adj_ = [np.mean([v[a] == v[a + 1] for v in V]) for a in range(K - 1)]
    nonadj = [np.mean([v[a] == v[b] for v in V]) for a, b in combinations(range(K), 2) if b - a > 1]
    P(f"- Pairwise verdict agreement across the {len(ag)} position pairs: range {min(ag):.3f}–{max(ag):.3f}; "
      f"adjacent mean {np.mean(adj_):.3f} vs non-adjacent mean {np.mean(nonadj):.3f}")
    # permutation test: max deviation of positional accuracy under within-instance permutation
    rng = np.random.default_rng(0); obs = np.ptp(corr.mean(0)); cnt = 0; B = 5000
    for _ in range(B):
        perm = np.array([rng.permutation(row) for row in corr])
        cnt += np.ptp(perm.mean(0)) >= obs - 1e-12
    P(f"- Permutation test of the accuracy range across positions (B={B}): observed range {obs:.3f}, p = {cnt/B:.3f}")
position_block("LLMBar canonical pool, test split", [(x["methods"]["SelfConsistency"]["votes"], x["gold"]) for x in T])
jb = jl("external_judgebench.jsonl")
position_block("JudgeBench pool", [(votes_of(r["pool"]), r["gold"]) for r in jb])
for f in ("repeat_pool_run2.jsonl", "repeat_pool_run3.jsonl"):
    rp = jl(f); position_block(f"Repeated pool {f[-7]}", [(votes_of(r["pool"]), r["gold"]) for r in rp])

# ---------- S3 ----------
P("\n## S3. Forced-choice Direct by subset (clean run, 22 July)")
fc = jl("clean_direct_fc.jsonl"); bs = {}
for r in fc: bs.setdefault(r["subset"], []).append(r["verdict"] == r["gold"])
for s in ("Natural", "Neighbor", "GPTInst", "GPTOut", "Manual"):
    P(f"- {s}: n={len(bs[s])}, accuracy {np.mean(bs[s]):.3f}")

# ---------- S4 ----------
P("\n## S4. Binary-correctness majority vs deployed modal aggregation")
mism = [x["iid"] for x in T if (sum(v == x["gold"] for v in x["methods"]["SelfConsistency"]["votes"]) >= 3)
        != bool(x["methods"]["SelfConsistency"]["correct"])]
P(f"- Test split: instances where I(c_i>K/2) differs from the deployed modal verdict's correctness: {len(mism)}")
# also JudgeBench and repeat pools (modal = Counter.most_common first-occurrence)
for name, rows in (("JudgeBench", [(votes_of(r["pool"]), r["gold"]) for r in jb]),
                   ("Repeated pool 2", [(votes_of(r["pool"]), r["gold"]) for r in jl("repeat_pool_run2.jsonl")]),
                   ("Repeated pool 3", [(votes_of(r["pool"]), r["gold"]) for r in jl("repeat_pool_run3.jsonl")])):
    mm = sum((sum(v == g for v in V) >= 3) != (Counter(V).most_common(1)[0][0] == g) for V, g in rows)
    modal = sum(1 for V, _ in rows if len(Counter(V)) > 1 and sorted(Counter(V).values())[-1] == sorted(Counter(V).values())[-2])
    P(f"- {name}: modal ties {modal}, binary-vs-modal mismatches {mm}")

# ---------- S5 ----------
P("\n## S5. Blinded human-audit kit")
raw_items = {}
for ds in SUB:
    for i, l in enumerate(open(os.path.join(HERE, ds), encoding="utf-8")):
        raw_items[f"{SUB[ds]}_{i:03d}"] = json.loads(l)
rows = [r for r in csv.DictReader(open(os.path.join(HERE, "results_final.csv"), encoding="utf-8"))
        if r["strategy"] == "SC-CoT" and r["split"] == "test"]
pers = []; stab = []
for r in rows:
    vs = r["votes"].split("|"); c = sum(v == r["gold_label"] for v in vs)
    if len(set(vs)) == 1 and c == 0: pers.append(r["instance_id"])
sb = {r["iid"]: r for r in jl("order_swap_stageB.jsonl")}
ctrl = [i for i, r in sb.items() if r["role"] == "matched_control"]
assert len(pers) == 37 and len(ctrl) == 37
items = [(i, "K-persistent") for i in pers] + [(i, "matched-control") for i in ctrl]
random.Random(20261001).shuffle(items)
AD = os.path.normpath(os.path.join(HERE, "..", "human_audit_v19")); os.makedirs(AD, exist_ok=True)
import openpyxl
from openpyxl.styles import Alignment, Font
def sheet(path, who):
    wb = openpyxl.Workbook(); ws = wb.active; ws.title = "audit"
    hdr = ["audit_id", "instruction", "response_A", "response_B",
           "Q1_better_response (A / B / both acceptable / neither)",
           "Q2_confidence (clear / arguable / problematic)", "Q3_note (optional)"]
    ws.append(hdr)
    for k, (iid, _) in enumerate(items, 1):
        it = raw_items[iid]
        ws.append([f"AUD{k:03d}", it["x"], it["a"], it["b"], "", "", ""])
    for col, w in zip("ABCDEFG", (10, 60, 60, 60, 22, 22, 30)):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row: c.alignment = Alignment(wrap_text=True, vertical="top")
    for c in ws[1]: c.font = Font(bold=True)
    g = wb.create_sheet("instructions")
    for line in [f"Annotator: {who}",
                 "Read each instruction and the two responses. Do not consult other annotators, the benchmark, or any model output.",
                 "Q1: Which response better follows the instruction? Choose A, B, 'both acceptable', or 'neither'.",
                 "Q2: How clear is that judgement? clear = one response is plainly better; arguable = reasonable people could disagree; problematic = the item is flawed (e.g. both wrong, instruction ambiguous).",
                 "Items are in random order; the set mixes several kinds of cases. Gold labels and model verdicts are hidden."]:
        g.append([line])
    g.column_dimensions["A"].width = 140
    wb.save(path)
sheet(os.path.join(AD, "audit_sheet_annotator1.xlsx"), "Annotator 1")
sheet(os.path.join(AD, "audit_sheet_annotator2.xlsx"), "Annotator 2")
with open(os.path.join(AD, "audit_key_DO_NOT_SHARE.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.writer(f); w.writerow(["audit_id", "instance_id", "group", "gold", "sc_cot_verdict"])
    for k, (iid, grp) in enumerate(items, 1):
        x = byid[iid]; w.writerow([f"AUD{k:03d}", iid, grp, x["gold"], x["methods"]["SelfConsistency"]["verdict"]])
P(f"- Wrote 2 annotator sheets ({len(items)} items: 37 K-persistent + 37 matched controls, shuffled seed 20261001) and a hidden key to human_audit_v19/")

open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))

# ---------- S6: JudgeBench under binary-correctness vs deployed modal aggregation ----------
L6 = ["\n## S6. JudgeBench decomposition: binary-correctness majority vs deployed modal aggregation"]
pool = lambda r: r["pool"] if isinstance(r["pool"], list) else votes_of(r["pool"])
cj = np.array([sum(v == r["gold"] for v in pool(r)) for r in jb]); p1 = cj / 5
binm = (cj >= 3).astype(float)
modm = np.array([float(Counter(pool(r)).most_common(1)[0][0] == r["gold"]) for r in jb])
rng6 = np.random.default_rng(0); ix6 = rng6.integers(0, len(jb), (5000, len(jb)))
for nm, mv in (("binary I(c_i>K/2)", binm), ("deployed modal, first-occurrence", modm)):
    d = mv - p1
    L6.append(f"- {nm}: K=5 acc {mv.mean():.4f}, gain {d.mean():+.4f} [{np.quantile(d[ix6].mean(1),.025):+.4f}, "
              f"{np.quantile(d[ix6].mean(1),.975):+.4f}], R_correctable {np.clip(d,0,None).mean():.4f}, "
              f"R_harmful {np.clip(-d,0,None).mean():.4f}")
open(OUT, "a", encoding="utf-8").write("\n".join(L6) + "\n"); print("\n".join(L6))

# ---------- S7: open-weight judges, binary vs modal ----------
L7 = ["\n## S7. Open-weight judges: modal ties and gain under both aggregation rules"]
for f, name in (("ollama_phi4_14b.jsonl", "Phi-4 14B"), ("ollama_qwen2_5_7b.jsonl", "Qwen2.5 7B"),
                ("ollama_gemma3_12b.jsonl", "Gemma 3 12B"), ("ollama_llama3_1_8b.jsonl", "Llama 3.1 8B")):
    Rw = jl(f); c7 = np.array([sum(v == r["gold"] for v in r["pool"]) for r in Rw]); q = c7 / 5
    b7 = (c7 >= 3).astype(float) - q
    m7 = np.array([float(Counter(r["pool"]).most_common(1)[0][0] == r["gold"]) for r in Rw]) - q
    mt = sum(1 for r in Rw if len(Counter(r["pool"])) > 1 and sorted(Counter(r["pool"]).values())[-1] == sorted(Counter(r["pool"]).values())[-2])
    ix7 = np.random.default_rng(0).integers(0, len(Rw), (5000, len(Rw)))
    ci = lambda d: f"[{np.quantile(d[ix7].mean(1),.025):+.3f}, {np.quantile(d[ix7].mean(1),.975):+.3f}]"
    rg = ((c7 > 0) & (c7 < 5)).mean(); dv = np.mean([len(set(r["pool"])) > 1 for r in Rw])
    L7.append(f"- {name}: modal ties {mt}; binary gain {b7.mean():+.3f} {ci(b7)}; modal gain {m7.mean():+.3f} {ci(m7)}; "
              f"R_gold {rg:.2f}; D_vote {dv:.2f}")
open(OUT, "a", encoding="utf-8").write("\n".join(L7) + "\n"); print("\n".join(L7))
