# -*- coding: utf-8 -*-
"""P0-1: Regenerate every manuscript table/number from results_final.csv.

Outputs numbers_for_manuscript.md — the single source all manuscript numbers are
copied from. Includes: Table 1 (accuracy + 95% bootstrap CI + kappa + MCC),
Table 2 (paired McNemar exact + Holm + paired bootstrap CI + TOST equivalence),
Table 3 (per-subset), failure taxonomy (resolves the 71% vs 73% discrepancy),
vote-margin reliability (ECE/Brier).
"""
from __future__ import annotations
import csv, json, math, os
from collections import defaultdict
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "results_final.csv")
OUT = os.path.join(HERE, "numbers_for_manuscript.md")
RNG = np.random.default_rng(0)
B = 5000
STRATS = ["DTT-Sym", "Direct", "Decomp", "Single-CoT", "SC-CoT"]
COMPARISONS = [  # (A, B) reporting A - B; Holm over these five
    ("SC-CoT", "Single-CoT"),
    ("SC-CoT", "Decomp"),
    ("SC-CoT", "Direct"),
    ("Single-CoT", "Decomp"),
    ("DTT-Sym", "Direct"),
]
EQ_DELTA = 0.02  # pre-registered equivalence margin (P1-10)

def load():
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    test = [r for r in rows if r["split"] == "test"]
    by = defaultdict(dict)  # instance_id -> strategy -> row
    for r in test:
        by[r["instance_id"]][r["strategy"]] = r
    ids = sorted(by)
    return by, ids

def acc_ci(corr):
    corr = np.asarray(corr, float)
    boots = RNG.choice(corr, (B, len(corr))).mean(axis=1)
    return corr.mean(), np.percentile(boots, 2.5), np.percentile(boots, 97.5)

def kappa_mcc(gold, pred):
    labs = ["A", "B", "tie"]
    g = [labs.index(x) for x in gold]; p = [labs.index(x) for x in pred]
    from sklearn.metrics import cohen_kappa_score, matthews_corrcoef
    return cohen_kappa_score(g, p), matthews_corrcoef(g, p)

def mcnemar_exact(b, c):
    n = b + c
    if n == 0: return 1.0
    return min(1.0, 2 * stats.binom.cdf(min(b, c), n, 0.5))

def paired_delta_ci(ca, cb):
    d = np.asarray(ca, float) - np.asarray(cb, float)
    idx = RNG.integers(0, len(d), (B, len(d)))
    boots = d[idx].mean(axis=1)
    return d.mean(), np.percentile(boots, 2.5), np.percentile(boots, 97.5), boots

def holm(ps):
    order = np.argsort(ps); out = [0.0] * len(ps); prev = 0.0
    for rank, i in enumerate(order):
        adj = min(1.0, (len(ps) - rank) * ps[i]); adj = max(adj, prev)
        out[i] = adj; prev = adj
    return out

def main():
    by, ids = load()
    L = [f"# Manuscript numbers — canonical run `main_20260615` (gpt-4o, N_test={len(ids)})",
         f"", f"> Generated by analyze_final.py from results_final.csv. Bootstrap B={B}, seed 0.", ""]

    # ---- Table 1
    corr = {s: [int(by[i][s]["correct"]) for i in ids] for s in STRATS}
    gold = [by[i]["Direct"]["gold_label"] for i in ids]
    L += ["## Table 1 — Pooled test accuracy", "",
          "| Strategy | Accuracy [95% CI] | kappa | MCC |", "|---|---|---|---|"]
    for s in STRATS:
        a, lo, hi = acc_ci(corr[s])
        pred = [by[i][s]["predicted_label"] for i in ids]
        k, m = kappa_mcc(gold, pred)
        L.append(f"| {s} | {a:.3f} [{lo:.3f}, {hi:.3f}] | {k:.2f} | {m:.2f} |")

    # ---- Table 2
    L += ["", "## Table 2 — Paired tests (McNemar exact, Holm over 5; paired bootstrap CI; TOST d=+-0.02)", "",
          "| Comparison | dAcc | 95% paired CI | b/c | p (raw) | p (Holm) | sig | TOST equivalent? |",
          "|---|---|---|---|---|---|---|---|"]
    raw_ps, rows2 = [], []
    for A, Bm in COMPARISONS:
        ca, cb = corr[A], corr[Bm]
        b = sum(1 for x, y in zip(ca, cb) if x and not y)
        c = sum(1 for x, y in zip(ca, cb) if not x and y)
        p = mcnemar_exact(b, c)
        d, lo, hi, boots = paired_delta_ci(ca, cb)
        # TOST via bootstrap: equivalent if 90% CI within +-delta (two one-sided at 5%)
        lo90, hi90 = np.percentile(boots, 5), np.percentile(boots, 95)
        eq = (lo90 > -EQ_DELTA) and (hi90 < EQ_DELTA)
        raw_ps.append(p); rows2.append((A, Bm, d, lo, hi, b, c, p, eq, lo90, hi90))
    hp = holm(raw_ps)
    for (A, Bm, d, lo, hi, b, c, p, eq, lo90, hi90), ph in zip(rows2, hp):
        L.append(f"| {A} - {Bm} | {d:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {b}/{c} | {p:.2g} | {ph:.2g} | "
                 f"{'yes' if ph < 0.05 else 'no'} | {'yes' if eq else 'no'} (90% CI [{lo90:+.3f},{hi90:+.3f}]) |")

    # ---- Table 3 per subset
    subsets = sorted({by[i]["Direct"]["subset"] for i in ids},
                     key=lambda s: ["Natural", "Neighbor", "GPTInst", "GPTOut", "Manual"].index(s))
    L += ["", "## Table 3 — Per-subset test accuracy", "",
          "| Subset (n) | " + " | ".join(STRATS) + " |", "|---|" + "---|" * len(STRATS)]
    for sub in subsets:
        sids = [i for i in ids if by[i]["Direct"]["subset"] == sub]
        cells = [f"{np.mean([int(by[i][s]['correct']) for i in sids]):.3f}" for s in STRATS]
        L.append(f"| {sub} ({len(sids)}) | " + " | ".join(cells) + " |")

    # ---- Failure taxonomy (SC-CoT errors) — resolves 71% vs 73%
    errs = [i for i in ids if not int(by[i]["SC-CoT"]["correct"])]
    def longer_chosen(i):
        r = by[i]["SC-CoT"]; v = r["predicted_label"]
        la, lb = int(r["candidate_A_length"]), int(r["candidate_B_length"])
        return (v == "A" and la > lb) or (v == "B" and lb > la)
    def unanimous(i):
        vs = by[i]["SC-CoT"]["votes"].split("|")
        return len(set(vs)) == 1
    n = len(errs)
    u = sum(unanimous(i) for i in errs)
    lg = sum(longer_chosen(i) for i in errs)
    both = sum(unanimous(i) and longer_chosen(i) for i in errs)
    split = sum(not unanimous(i) for i in errs)
    ties = sum(by[i]["SC-CoT"]["predicted_label"] == "tie" for i in errs)
    err_by_sub = defaultdict(int)
    for i in errs: err_by_sub[by[i]["SC-CoT"]["subset"]] += 1
    L += ["", f"## Failure taxonomy — SC-CoT test errors: {n}/{len(ids)} = {n/len(ids):.1%}", "",
          "| Category | Count | % of errors |", "|---|---|---|",
          f"| Unanimous (5/5 wrong) | {u} | {u/n:.0%} |",
          f"| Longer response chosen | {lg} | {lg/n:.0%} |",
          f"| Unanimous AND longer | {both} | {both/n:.0%} |",
          f"| Split vote | {split} | {split/n:.0%} |",
          f"| Tie verdict | {ties} | {ties/n:.0%} |",
          "", f"Errors by subset: " + ", ".join(f"{k} {v}" for k, v in
              sorted(err_by_sub.items(), key=lambda x: -x[1]))]

    # ---- Vote-margin reliability
    L += ["", "## Vote-margin reliability (SC-CoT, test)", "",
          "| Vote | Confidence | Accuracy | Count |", "|---|---|---|---|"]
    groups = defaultdict(list)
    for i in ids:
        r = by[i]["SC-CoT"]; m = int(float(r["vote_margin"]))
        groups[m].append(int(r["correct"]))
    ece = 0.0; brier = 0.0; N = len(ids)
    for m in sorted(groups, reverse=True):
        conf = m / 5; accs = groups[m]; a = np.mean(accs)
        L.append(f"| {m}-{5-m} | {conf:.2f} | {a:.3f} | {len(accs)} |")
        ece += len(accs) / N * abs(conf - a)
        brier += sum((conf - c) ** 2 for c in accs) / N
    L += ["", f"ECE = {ece:.3f}, Brier = {brier:.3f}"]

    # ---- Key sentences for the manuscript
    d_sc_cot = rows2[0]
    L += ["", "## Anchor numbers (copy these into the manuscript)", "",
          f"- SC-CoT vs Single-CoT: d={d_sc_cot[2]:+.3f}, 95% CI [{d_sc_cot[3]:+.3f}, {d_sc_cot[4]:+.3f}], "
          f"b/c={d_sc_cot[5]}/{d_sc_cot[6]}, p(Holm)={hp[0]:.2g} -> net +{d_sc_cot[5]-d_sc_cot[6]} correct of {len(ids)}",
          f"- Unanimous errors: {u}/{n} = {u/n:.0%}; longer chosen: {lg}/{n} = {lg/n:.0%}; both: {both}/{n} = {both/n:.0%}",
          f"- Equivalence at +-{EQ_DELTA:.0%}: {'ESTABLISHED' if rows2[0][8] else 'NOT established'} "
          f"(90% CI [{d_sc_cot[9]:+.3f}, {d_sc_cot[10]:+.3f}])"]

    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"wrote {OUT}")

if __name__ == "__main__":
    main()
