# -*- coding: utf-8 -*-
"""v1.8 revision analyses (offline; no API calls).

Adds the quantities requested in the v1.8 methodological review:
  R1  finite-pool vs latent-probability reading of c_i = 0 (Clopper-Pearson bounds)
  R2  latent-probability layer: plug-in and Jeffreys-posterior projections of
      G_K(p) = M_K(p) - p for a fresh committee
  R3  gold-conditioned reachability (R_gold) vs label-free vote dispersion (D_vote)
  R4  repeated pools: c_i = 0 in one pool vs correct votes in other pools;
      between-pool variability of the voting effect
  R5  two-level bootstrap (instances -> within-instance votes) for the voting effect
  R6  matched-pair exact McNemar tests for the order-swap and constraint probes
  R7  aggregation edge cases (modal ties), parser ties, logged model strings and dates
Writes revision_numbers_v18.md next to this script.
"""
from __future__ import annotations
import csv, json, os
from collections import Counter
from math import comb
import numpy as np
from scipy.stats import beta, binomtest, fisher_exact

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "revision_numbers_v18.md")
K = 5
L = []
def P(s=""): L.append(s)

def M(p, k=K):
    return sum(comb(k, j) * p**j * (1 - p)**(k - j) for j in range(k // 2 + 1, k + 1))

def cp(x, n, a=0.05):
    lo = 0.0 if x == 0 else beta.ppf(a / 2, x, n - x + 1)
    hi = 1.0 if x == n else beta.ppf(1 - a / 2, x + 1, n - x)
    return lo, hi

def jl(name):
    return [json.loads(l) for l in open(os.path.join(HERE, name), encoding="utf-8") if l.strip()]

def votes_of(s):
    return [v.strip(" '\"") for v in s.strip("[]").split(",")] if isinstance(s, str) else s

# ---------- canonical records ----------
rec = json.load(open(os.path.join(HERE, "records.json"), encoding="utf-8"))
ALL, T = [], []
for ds, items in rec["datasets"].items():
    sub = ds.replace("full_", "").replace(".jsonl", "")
    for idx, x in enumerate(items):
        x = dict(x); x["_sub"] = sub; ALL.append(x)
        if x["split"] == "test": T.append(x)
N = len(T)
c = np.array([sum(v == x["gold"] for v in x["methods"]["SelfConsistency"]["votes"]) for x in T])
d = (c > K / 2).astype(float) - c / K
P("# v1.8 revision numbers (generated by analyze_v18_revisions.py)")
P(f"\nCanonical run judge string: `{rec['judge']}`; held-out test N={N}.")
P(f"Realised-pool voting effect Δ_MV = {d.mean():.5f} ({d.sum():.2f} cases); "
  f"corrected {d[d>0].sum():.2f}, harmed {-d[d<0].sum():.2f}.")

# ---------- R1 ----------
P("\n## R1. Finite-pool reading of c_i = 0")
lo, hi = cp(0, K)
P(f"- 0/{K}: two-sided 95% Clopper-Pearson interval for p_i = [{lo:.3f}, {hi:.3f}].")
P(f"- P(c_i = 0 | p_i = 0.5) = {0.5**K:.4f} (one-sided test of p_i >= 0.5).")
lo1, hi1 = cp(1, K); P(f"- 1/{K}: 95% CP interval [{lo1:.3f}, {hi1:.3f}].")
lo15, hi15 = cp(0, 15); P(f"- 0/15: 95% CP interval [{lo15:.3f}, {hi15:.3f}].")
for k in (5, 9, 15, 25):
    P(f"- M_{k}(p) at p = 0.10 / 0.30 / 0.45: {M(0.10,k):.4f} / {M(0.30,k):.4f} / {M(0.45,k):.4f}")

# ---------- R2 ----------
P("\n## R2. Latent-probability projections for a fresh K-committee")
for k in (3, 5, 9):
    g_plug = np.mean([M(ci / K, k) - ci / K for ci in c])
    P(f"- Plug-in p̂_i = c_i/K, G_{k}: mean {g_plug:+.5f} ({g_plug*N:+.2f} cases)")
rng = np.random.default_rng(0)
S = 4000
pj = rng.beta(c[:, None] + 0.5, K - c[:, None] + 0.5, size=(N, S))
for k in (3, 5, 9):
    Mk = sum(comb(k, j) * pj**j * (1 - pj)**(k - j) for j in range(k // 2 + 1, k + 1))
    g = (Mk - pj).mean(axis=0)
    P(f"- Jeffreys posterior (Beta(c+½, K−c+½)), G_{k}: mean {g.mean():+.5f}, "
      f"95% posterior interval [{np.quantile(g,.025):+.5f}, {np.quantile(g,.975):+.5f}]")
pers = c == 0
P(f"- Persistent instances (c_i=0, n={pers.sum()}): Jeffreys posterior mean p = {(0.5)/(K+1):.3f}; "
  f"posterior P(p_i >= 0.5) = {1-beta.cdf(0.5,0.5,K+0.5):.4f} per instance.")

# ---------- R3 ----------
P("\n## R3. Gold-conditioned reachability vs label-free dispersion")
nonun = np.array([len(set(x["methods"]["SelfConsistency"]["votes"])) > 1 for x in T])
rgold = (c > 0) & (c < K)
P(f"- R_gold (0<c_i<K): {rgold.sum()}/{N} = {rgold.mean():.3f}")
P(f"- D_vote (non-unanimous labels): {nonun.sum()}/{N} = {nonun.mean():.3f}")
P(f"- D_vote & not R_gold: {(nonun & ~rgold).sum()} (all with c_i=0); R_gold & not D_vote: {(rgold & ~nonun).sum()}")
pref3 = np.array([len(set(x["methods"]["SelfConsistency"]["votes"][:3])) == 1 for x in T])
P(f"- 3-0 prefix: {pref3.sum()}/{N}; mean calls 3→5 = {np.where(pref3,3,5).mean():.3f}")

# ---------- R4 ----------
P("\n## R4. Repeated independent pools (N=100, seed 7)")
ids = json.load(open(os.path.join(HERE, "splits", "repeat_pool_100_ids.json"), encoding="utf-8"))["ids"]
byid = {}
for ds, items in rec["datasets"].items():
    sub = {"full_natural.jsonl": "Natural", "full_neighbor.jsonl": "Neighbor", "full_gptinst.jsonl": "GPTInst",
           "full_gptout.jsonl": "GPTOut", "full_manual.jsonl": "Manual"}[ds]
    for i, x in enumerate(items):
        byid[f"{sub}_{i:03d}"] = x
r2 = {r["iid"]: r for r in jl("repeat_pool_run2.jsonl")}
r3 = {r["iid"]: r for r in jl("repeat_pool_run3.jsonl")}
gold = {i: byid[i]["gold"] for i in ids}
for i in ids[:3]:
    assert r2[i]["gold"] == gold[i], "id mapping mismatch"
pools = [{i: byid[i]["methods"]["SelfConsistency"]["votes"] for i in ids},
         {i: votes_of(r2[i]["pool"]) for i in ids}, {i: votes_of(r3[i]["pool"]) for i in ids}]
cc = np.array([[sum(v == gold[i] for v in p[i]) for i in ids] for p in pools])  # 3 x 100
gains = [((row > 2.5) - row / 5).mean() for row in cc]
P(f"- Per-pool Δ_MV: {', '.join(f'{g:+.3f}' for g in gains)}; mean {np.mean(gains):+.4f}, "
  f"between-pool SD {np.std(gains, ddof=1):.4f}")
P(f"- Per-pool R_gold: {', '.join(f'{((r>0)&(r<5)).mean():.2f}' for r in cc)}; "
  f"per-pool R_persistent: {', '.join(str(int((r==0).sum())) for r in cc)}")
tot = cc.sum(axis=0)
p0 = cc[0] == 0
other_hit = (cc[1][p0] > 0) | (cc[2][p0] > 0)
P(f"- c_i=0 in canonical pool: {p0.sum()}; of these, ≥1 correct vote in another pool: {other_hit.sum()}")
anyz = (cc == 0).any(axis=0)
P(f"- c_i=0 in ≥1 pool: {anyz.sum()}; c_i=0 in all 3 pools (0/15): {(cc==0).all(axis=0).sum()}")
P(f"- Pooled 15-vote counts among the {anyz.sum()} ever-persistent instances: {sorted(tot[anyz].tolist())}")
sw = []
for j in range(len(ids)):
    for a in range(3):
        for b in range(3):
            if a != b and cc[a, j] == 0:
                sw.append(cc[b, j] > 0)
P(f"- Pool-to-pool: P(≥1 correct in another pool | c_i=0 in a given pool) = {np.mean(sw):.3f} ({sum(sw)}/{len(sw)} ordered pairs)")
g15 = np.mean([M(t / 15, 15) - t / 15 for t in tot])
P(f"- Plug-in on pooled 15 votes, G_5(p̂): {np.mean([M(t/15,5)-t/15 for t in tot]):+.4f}")

# ---------- R5 ----------
P("\n## R5. Bootstrap intervals for the voting effect (B=5000, seed 0)")
B = 5000
rng = np.random.default_rng(0)
idx = rng.integers(0, N, size=(B, N))
inst = d[idx].mean(axis=1)
P(f"- Instance-level bootstrap (realised pool): [{np.quantile(inst,.025):+.4f}, {np.quantile(inst,.975):+.4f}]")
cstar = rng.binomial(K, (c / K)[idx])
two = ((cstar > K / 2) - cstar / K).mean(axis=1)
P(f"- Two-level nonparametric (instances, then votes with replacement): mean {two.mean():+.4f}, "
  f"[{np.quantile(two,.025):+.4f}, {np.quantile(two,.975):+.4f}]")
pj = rng.beta(c[idx] + 0.5, K - c[idx] + 0.5)
cj = rng.binomial(K, pj)
twoj = ((cj > K / 2) - cj / K).mean(axis=1)
P(f"- Two-level Jeffreys (instances, p_i ~ posterior, fresh K=5 votes): mean {twoj.mean():+.4f}, "
  f"[{np.quantile(twoj,.025):+.4f}, {np.quantile(twoj,.975):+.4f}]")
P(f"- Share of two-level Jeffreys replicates ≤ 0: {(twoj<=0).mean():.3f}")

# ---------- R6 ----------
P("\n## R6. Matched-pair tests (order swap K=5; constraint-focused T=0)")
rows = [r for r in csv.DictReader(open(os.path.join(HERE, "results_final.csv"), encoding="utf-8"))
        if r["strategy"] == "SC-CoT" and r["split"] == "test"]
for r in rows:
    vs = r["votes"].split("|"); r["unan"] = len(set(vs)) == 1
    r["c_i"] = sum(v == r["gold_label"] for v in vs)
    r["gap"] = abs(int(r["candidate_A_length"]) - int(r["candidate_B_length"]))
pers_r = [r for r in rows if r["unan"] and r["c_i"] == 0]
stab = [r for r in rows if r["c_i"] == 5]
gaps = sorted(r["gap"] for r in rows); t1, t2 = gaps[len(gaps)//3], gaps[2*len(gaps)//3]
ter = lambda g: 0 if g <= t1 else (1 if g <= t2 else 2)
rr = np.random.default_rng(0); used, pairs = set(), []
for p in pers_r:
    pool = [s for s in stab if s["subset"] == p["subset"] and s["gold_label"] == p["gold_label"]
            and ter(s["gap"]) == ter(p["gap"]) and s["instance_id"] not in used]
    relaxed = False
    if not pool:
        relaxed = True
        pool = [s for s in stab if s["subset"] == p["subset"] and s["gold_label"] == p["gold_label"]
                and s["instance_id"] not in used]
    if pool:
        m = pool[int(rr.integers(len(pool)))]; used.add(m["instance_id"])
        pairs.append((p["instance_id"], m["instance_id"], relaxed))
P(f"- Reconstructed pairs: {len(pairs)} (tercile relaxed for {sum(x[2] for x in pairs)})")
sb = {r["iid"]: r for r in jl("order_swap_stageB.jsonl")}
roles = Counter(r["role"] for r in sb.values())
assert all(p in sb and m in sb for p, m, _ in pairs), "pair ids not found in stage B journal"
assert all(sb[p]["role"] != "matched_control" and sb[m]["role"] == "matched_control" for p, m, _ in pairs)
def maj_correct(r):
    v = votes_of(r["verdicts_original_frame"]); return Counter(v).most_common(1)[0][0] == r["gold"]
def report(name, ok_p, ok_m):
    rec_p = np.array([ok_p(p) for p, _, _ in pairs]); flip_m = np.array([not ok_m(m) for _, m, _ in pairs])
    b = int((rec_p & ~flip_m).sum()); cdis = int((~rec_p & flip_m).sum())
    both = int((rec_p & flip_m).sum()); nei = int((~rec_p & ~flip_m).sum())
    pm = binomtest(b, b + cdis, 0.5).pvalue if b + cdis else 1.0
    pf = fisher_exact([[rec_p.sum(), len(pairs) - rec_p.sum()], [flip_m.sum(), len(pairs) - flip_m.sum()]])[1]
    P(f"- {name}: persistent recovered {rec_p.sum()}/{len(pairs)}, control flipped {flip_m.sum()}/{len(pairs)}; "
      f"pair table (rec&noflip={b}, norec&flip={cdis}, both={both}, neither={nei}); "
      f"exact McNemar p = {pm:.4f}; Fisher (unpaired) p = {pf:.4f}")
report("Order swap K=5", lambda i: maj_correct(sb[i]), lambda i: maj_correct(sb[i]))
rb = {r["iid"]: r for r in jl("causal_rubric.jsonl")}
report("Constraint-focused T=0", lambda i: rb[i]["verdict"] == rb[i]["gold"], lambda i: rb[i]["verdict"] == rb[i]["gold"])
os_rec = {p for p, _, _ in pairs if maj_correct(sb[p])}
rb_rec = {p for p, _, _ in pairs if rb[p]["verdict"] == rb[p]["gold"]}
cf = {r["iid"]: r for r in jl("causal_counterfactual.jsonl")}
cf_rec = {i for i, r in cf.items() if r["verdict_after_compress"] == r["gold"] or r["verdict_after_expand"] == r["gold"]}
anyrec = os_rec | rb_rec | cf_rec
P(f"- Overlap order∩constraint = {len(os_rec & rb_rec)}; recovered by ≥1 intervention = {len(anyrec)}/37; none = {37-len(anyrec)}")
lo, hi = cp(37 - len(anyrec), 37); P(f"- Survived all: 95% CP [{lo:.3f}, {hi:.3f}]")
comp = [int(r["len_wrong_comp"]) / int(r["len_wrong"]) for r in cf.values()]
exp_ = [int(r["len_gold_exp"]) / int(r["len_gold"]) for r in cf.values()]
P(f"- Counterfactual length ratios: compress mean {np.mean(comp):.2f} (median {np.median(comp):.2f}); "
  f"expand mean {np.mean(exp_):.2f} (median {np.median(exp_):.2f})")
gold_longer = sum(int(r["len_gold_exp"]) > int(r["len_wrong"]) for r in cf.values())
P(f"- After expansion, gold longer than the selected incorrect response in {gold_longer}/31")

# ---------- R7 ----------
P("\n## R7. Aggregation, parsing, identifiers, dates")
pat = Counter(); modal = []
for x in ALL:
    v = x["methods"]["SelfConsistency"]["votes"]; s = tuple(sorted(Counter(v).values(), reverse=True)); pat[s] += 1
    if len(s) > 1 and s[0] == s[1]: modal.append((x["split"], v, x["gold"], x["methods"]["SelfConsistency"]["verdict"]))
P(f"- Vote-count patterns over 419: {dict(pat)}")
P(f"- Modal ties (e.g. 2-2-1): {modal}")
pt = Counter();
for x in T:
    pt["any tie vote"] += any(v == "tie" for v in x["methods"]["SelfConsistency"]["votes"])
P(f"- Test individual tie votes: {sum(v=='tie' for x in T for v in x['methods']['SelfConsistency']['votes'])}/{N*K}; "
  f"instances with ≥1 tie vote: {pt['any tie vote']}")
for m in ("Vanilla", "CoT", "SelfConsistency"):
    P(f"- Test tie verdicts, {m}: {sum(x['methods'][m]['verdict']=='tie' for x in T)}")
for f in ("clean_direct_fc.jsonl", "clean_singlecot.jsonl"):
    js = jl(f); P(f"- {f}: parse_status {dict(Counter(r.get('parse_status') for r in js))}")
for f in ("order_swap_stageA.jsonl", "order_swap_stageB.jsonl", "clean_direct_fc.jsonl", "clean_singlecot.jsonl",
          "external_judgebench.jsonl", "repeat_pool_run2.jsonl", "repeat_pool_run3.jsonl",
          "causal_rubric.jsonl", "causal_counterfactual.jsonl"):
    js = jl(f); ts = sorted(r["ts"] for r in js)
    P(f"- {f}: n={len(js)}, model={dict(Counter(r['model'] for r in js))}, ts {ts[0]} → {ts[-1]}")
for f in ("splits/instance_ids.json", "splits/judgebench_120_ids.json", "splits/repeat_pool_100_ids.json",
          "records.json", "run_records.py", "run_experiment.py"):
    import datetime
    P(f"- file mtime {f}: {datetime.datetime.fromtimestamp(os.path.getmtime(os.path.join(HERE,f))).isoformat(timespec='seconds')}")

open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))

# ---------- R8: forced-choice Direct baseline (clean run, 22 Jul 2026) ----------
fc = jl("clean_direct_fc.jsonl")
y = np.array([r["verdict"] == r["gold"] for r in fc], float)
iid2 = {}
for ds, items in rec["datasets"].items():
    sub = {"full_natural.jsonl": "Natural", "full_neighbor.jsonl": "Neighbor", "full_gptinst.jsonl": "GPTInst",
           "full_gptout.jsonl": "GPTOut", "full_manual.jsonl": "Manual"}[ds]
    for i, x in enumerate(items):
        iid2[f"{sub}_{i:03d}"] = x
cot = np.array([iid2[r["iid"]]["methods"]["CoT"]["correct"] for r in fc], float)
scc = np.array([iid2[r["iid"]]["methods"]["SelfConsistency"]["correct"] for r in fc], float)
rg = np.random.default_rng(0); ix = rg.integers(0, len(y), (5000, len(y)))
L2 = ["\n## R8. Forced-choice Direct (clean run)",
      f"- Accuracy {y.mean():.3f}, 95% bootstrap CI [{np.quantile(y[ix].mean(1),.025):.3f}, {np.quantile(y[ix].mean(1),.975):.3f}]"]
for nm, z in (("Single-CoT", cot), ("SC-CoT", scc)):
    dd = z - y; b = int(((z == 1) & (y == 0)).sum()); cdis = int(((z == 0) & (y == 1)).sum())
    L2.append(f"- {nm} − Direct-FC: {dd.mean():+.3f}, CI [{np.quantile(dd[ix].mean(1),.025):+.3f}, "
              f"{np.quantile(dd[ix].mean(1),.975):+.3f}], b/c {b}/{cdis}, exact McNemar p {binomtest(b, b+cdis, .5).pvalue:.3f}")
from sklearn.metrics import cohen_kappa_score, matthews_corrcoef
gl = [r["gold"] for r in fc]; pr = [r["verdict"] for r in fc]
L2.append(f"- Cohen kappa {cohen_kappa_score(gl, pr):.2f}, MCC {matthews_corrcoef(gl, pr):.2f} (labels A/B/tie)")
open(OUT, "a", encoding="utf-8").write("\n".join(L2) + "\n"); print("\n".join(L2))
