# -*- coding: utf-8 -*-
"""v2.5 revision analyses (offline; no API calls, no local model calls).

  W1  What the within-pool estimator buys a practitioner: interval width of the voting gain
      estimated (a) from the pool (Delta_MV), (b) as majority minus one stochastic draw,
      (c) as majority minus the greedy T=0 judgment (the usual separate-run comparison),
      for every setting, with the instance count each alternative would need for the
      precision of (a).
  W2  Pilot-to-test use: the diagnosis computed on the development split (the pilot an
      evaluator would run first) against the same quantities on the test split.
  W3  Gains and errors introduced by candidate-order swapping on all 295 test instances
      (T=0, same session as the plain re-judgment), and the conditions of every
      re-judging comparison (date, time window, temperature, K, output cap, tie labels).
Uses the shared bootstrap of analyze_v24_revisions.py (same B and seed).
Writes revision_numbers_v25.md and revision_numbers_v25.json next to this script.
"""
from __future__ import annotations
import csv, json, os
from collections import Counter
import numpy as np
from scipy.stats import binomtest

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_MD = os.path.join(HERE, "revision_numbers_v25.md")
OUT_JS = os.path.join(HERE, "revision_numbers_v25.json")
K = 5
B = 100_000
SEED = 20261005
L: list[str] = []
J: dict = {"B": B, "seed": SEED}


def P(s=""):
    L.append(s)


def jl(n):
    return [json.loads(l) for l in open(os.path.join(HERE, n), encoding="utf-8") if l.strip()]


def votes_of(s):
    return [v.strip(" '\"") for v in s.strip("[]").split(",")] if isinstance(s, str) else list(s)


def boot(v):
    """Percentile bootstrap of a mean (same routine, B and seed as v2.4)."""
    v = np.asarray(v, float)
    n = len(v)
    rng = np.random.default_rng(SEED)
    reps = np.concatenate([v[rng.integers(0, n, (10_000, n))].mean(1) for _ in range(B // 10_000)])
    return float(v.mean()), float(np.quantile(reps, .025)), float(np.quantile(reps, .975)), float(reps.std(ddof=1))


def modal_first(v):
    return Counter(v).most_common(1)[0][0]


def mcn(b, c):
    return binomtest(b, b + c, 0.5).pvalue if b + c else 1.0


SUB = {"full_natural.jsonl": "Natural", "full_neighbor.jsonl": "Neighbor", "full_gptinst.jsonl": "GPTInst",
       "full_gptout.jsonl": "GPTOut", "full_manual.jsonl": "Manual"}
rec = json.load(open(os.path.join(HERE, "records.json"), encoding="utf-8"))
byid, ALL = {}, []
for ds, items in rec["datasets"].items():
    for i, x in enumerate(items):
        x = dict(x)
        x["iid"] = f"{SUB[ds]}_{i:03d}"
        x["subset"] = SUB[ds]
        byid[x["iid"]] = x
        ALL.append(x)
T = [x for x in ALL if x["split"] == "test"]
D = [x for x in ALL if x["split"] == "dev"]
assert len(T) == 295 and len(D) == 124
SCV = lambda x: x["methods"]["SelfConsistency"]["votes"]

P("# v2.5 revision numbers (generated by analyze_v25_revisions.py)")
P(f"\nShared bootstrap: percentile, B = {B:,}, seed {SEED}. Offline only; no API or local-model calls.")

# ================================================================= W1
P("\n## W1. Precision of three ways to estimate the voting gain (binary-correctness majority)")
P("(a) within-pool Delta_MV = I(c>K/2) - c/K; (b) majority minus one stochastic draw from the same pool "
  "(mean over the five draw positions); (c) majority minus the greedy T=0 judgment (separate decoding).")
P("N ratio = (width / width of (a))^2: the factor by which the instance count must grow to reach the precision of (a).")
SET = {}
SET["llmbar295"] = ("GPT-4o, LLMBar test split", [(SCV(x), x["gold"], bool(x["methods"]["CoT"]["correct"])) for x in T])
jb = jl("external_judgebench.jsonl")
SET["judgebench"] = ("GPT-4o, JudgeBench sample", [(votes_of(r["pool"]), r["gold"], r["greedy"] == r["gold"]) for r in jb])
for key, f, name in (("phi4", "ollama_phi4_14b.jsonl", "Phi-4 14B"), ("qwen", "ollama_qwen2_5_7b.jsonl", "Qwen2.5 7B"),
                     ("gemma", "ollama_gemma3_12b.jsonl", "Gemma 3 12B"), ("llama", "ollama_llama3_1_8b.jsonl", "Llama 3.1 8B")):
    SET[key] = (name + ", common 100-instance sample", [(r["pool"], r["gold"], r["greedy"] == r["gold"]) for r in jl(f)])
P("\n| Setting | N | (a) within-pool [95% CI] width | (b) majority - one draw: mean width (N ratio) | "
  "(c) majority - greedy: estimate [95% CI] width (N ratio) |")
P("|---|---|---|---|---|")
W1 = {}
for k, (name, rows) in SET.items():
    maj = np.array([sum(z == g for z in v) > K / 2 for v, g, _ in rows], float)
    c = np.array([sum(z == g for z in v) for v, g, _ in rows], float)
    a = boot(maj - c / K)
    wa = a[2] - a[1]
    bw, bpt = [], []
    for j in range(K):
        dj = maj - np.array([v[j] == g for v, g, _ in rows], float)
        t = boot(dj)
        bw.append(t[2] - t[1])
        bpt.append(t[0])
    wb = float(np.mean(bw))
    gr = np.array([gy for _, _, gy in rows], float)
    cc_ = boot(maj - gr)
    wc = cc_[2] - cc_[1]
    W1[k] = {"N": len(rows), "a": a, "width_a": wa, "b_point_range": [min(bpt), max(bpt)], "width_b_mean": wb,
             "width_b_range": [min(bw), max(bw)], "ratio_b": (wb / wa) ** 2, "c": cc_, "width_c": wc,
             "ratio_c": (wc / wa) ** 2}
    P(f"| {name} | {len(rows)} | {a[0]:+.4f} [{a[1]:+.3f}, {a[2]:+.3f}] {wa:.3f} | {wb:.3f} "
      f"(x{(wb / wa) ** 2:.1f}; point range {min(bpt):+.3f} to {max(bpt):+.3f}) | "
      f"{cc_[0]:+.3f} [{cc_[1]:+.3f}, {cc_[2]:+.3f}] {wc:.3f} (x{(wc / wa) ** 2:.1f}) |")
rb = [W1[k]["ratio_b"] for k in W1]
rc = [W1[k]["ratio_c"] for k in W1]
P(f"\n- N ratio, single-draw contrast: {min(rb):.1f} to {max(rb):.1f}; greedy contrast: {min(rc):.1f} to {max(rc):.1f}")
P("- (a) is the conditional expectation of (b) given c_i (average over the K draw positions), so its variance "
  "cannot exceed that of (b) (Rao-Blackwell); (c) also changes the decoding temperature, so it does not isolate aggregation.")
J["W1"] = W1

# ================================================================= W2
P("\n## W2. Pilot-to-test: the diagnosis on the development split versus the test split (canonical GPT-4o pool)")


def diag(items):
    c = np.array([sum(z == x["gold"] for z in SCV(x)) for x in items])
    d = (c > K / 2).astype(float) - c / K
    maj = c > K / 2
    sc_err = int((~maj).sum())
    pers = int((c == 0).sum())
    g = boot(d)
    sc_ok = np.array([x["methods"]["SelfConsistency"]["correct"] for x in items], float)
    cot_ok = np.array([x["methods"]["CoT"]["correct"] for x in items], float)
    sep = boot(sc_ok - cot_ok)
    return {"N": len(items), "acc_k1": float((c / K).mean()), "acc_k5": float(maj.mean()), "gain": g,
            "pos": float(np.clip(d, 0, None).mean()), "neg": float(np.clip(-d, 0, None).mean()),
            "R_gold": float(((c > 0) & (c < K)).mean()), "pers": pers, "pers_share": pers / len(items),
            "sc_err": sc_err, "pers_of_err": pers / sc_err if sc_err else float("nan"),
            "early_calls": float(np.mean([3 if len(set(SCV(x)[:3])) == 1 else 5 for x in items])),
            "sc_correct": int(sc_ok.sum()), "cot_correct": int(cot_ok.sum()), "sep": sep}


W2 = {"dev": diag(D), "test": diag(T)}
P("\n| Quantity | Development split (pilot) | Test split |")
P("|---|---|---|")
for lab, f in (("N", lambda s: f"{s['N']}"), ("Expected K=1 accuracy", lambda s: f"{s['acc_k1']:.3f}"),
               ("K=5 binary-majority accuracy", lambda s: f"{s['acc_k5']:.3f}"),
               ("Delta_MV [95% CI]", lambda s: f"{s['gain'][0]:+.4f} [{s['gain'][1]:+.3f}, {s['gain'][2]:+.3f}]"),
               ("Positive / negative mass", lambda s: f"{s['pos']:.4f} / {s['neg']:.4f} (offset {s['neg']/s['pos']:.0%})" if s['pos'] else "-"),
               ("R_gold", lambda s: f"{s['R_gold']:.3f}"),
               ("K-persistent count (share of items)", lambda s: f"{s['pers']} ({s['pers_share']:.3f})"),
               ("K-persistent share of K=5 errors", lambda s: f"{s['pers']}/{s['sc_err']} ({s['pers_of_err']:.0%})"),
               ("Early-stopping mean calls", lambda s: f"{s['early_calls']:.2f}"),
               ("Separate runs: SC-CoT - Single-CoT (T=0) [95% CI]",
                lambda s: f"{s['sep'][0]:+.4f} [{s['sep'][1]:+.3f}, {s['sep'][2]:+.3f}] ({s['sc_correct']} vs {s['cot_correct']} correct)")):
    P(f"| {lab} | {f(W2['dev'])} | {f(W2['test'])} |")
J["W2"] = W2

# ================================================================= W3
P("\n## W3. Order swap on the whole test split: gains and errors introduced, and comparison conditions")
sa = {r["iid"]: r for r in jl("order_swap_stageA.jsonl")}
cs = {r["iid"]: r for r in jl("clean_singlecot.jsonl")}
ids = [x["iid"] for x in T]
assert all(i in sa and i in cs for i in ids)
sw = np.array([votes_of(sa[i]["verdicts_original_frame"])[0] == sa[i]["gold"] for i in ids])
pr = np.array([cs[i]["verdict"] == cs[i]["gold"] for i in ids])
fixed, broken = int((sw & ~pr).sum()), int((~sw & pr).sum())
W3 = {"n": len(ids), "swap_correct": int(sw.sum()), "plain_correct": int(pr.sum()), "fixed": fixed, "broken": broken,
      "net": fixed - broken, "p": float(mcn(fixed, broken)), "net_ci": boot(sw.astype(float) - pr.astype(float))}
P(f"- All {len(ids)} test instances, one call at T=0: swapped order correct {int(sw.sum())}, plain re-judgment "
  f"correct {int(pr.sum())}; wrong->right after swapping {fixed}, right->wrong {broken}; net {fixed - broken:+d} "
  f"({W3['net_ci'][0]:+.4f} [{W3['net_ci'][1]:+.3f}, {W3['net_ci'][2]:+.3f}]); exact McNemar p = {W3['p']:.3f}")
canon = np.array([bool(byid[i]["methods"]["CoT"]["correct"]) for i in ids])
for lab, m in (("canonical Single-CoT wrong", ~canon), ("canonical Single-CoT right", canon)):
    f_, b_ = int((sw & ~pr & m).sum()), int((~sw & pr & m).sum())
    P(f"  - among items {lab} (n={int(m.sum())}): fixed {f_}, broken {b_}")
    W3[lab] = {"n": int(m.sum()), "fixed": f_, "broken": b_}
same = np.array([sa[i].get("same_choice", None) for i in ids])
tsa = sorted(sa[i]["ts"] for i in ids)
tcs = sorted(cs[i]["ts"] for i in ids)
P(f"- Time windows on all 295: swapped T=0 {tsa[0]} to {tsa[-1]}; plain re-judgment T=0 {tcs[0]} to {tcs[-1]}")
P(f"- Tie verdicts on all 295: swapped {sum(votes_of(sa[i]['verdicts_original_frame'])[0] == 'tie' for i in ids)}, "
  f"plain {sum(cs[i]['verdict'] == 'tie' for i in ids)}")
W3["ts"] = {"swap": [tsa[0], tsa[-1]], "plain": [tcs[0], tcs[-1]]}
J["W3"] = W3

# ================================================================= W4
P("\n## W4. Instrumented campaign of 13 July 2026 (run_campaign.py), not analysed in earlier versions")
P("Order randomized per instance (seed 1234, same order for all strategies); nine T=0.7 CoT samples per instance; "
  "stopped when the API quota was exhausted (gpt-4o-mini 416/419 instances, gpt-4o 206/419, gpt-4.1 none).")
from math import comb as _comb
W4 = {}
for m in ("gpt-4o-mini", "gpt-4o"):
    R = [r for r in jl(f"campaign_{m}.jsonl") if r["split"] == "test"]
    sc = [r["strategies"]["SC-CoT"] for r in R]
    first5_ok = sum(modal_first(s["pool"][:5]) == s["verdict"] for s in sc)
    rows = [(s["pool"][:5], r["gold"], bool(r["strategies"]["Single-CoT"]["correct"])) for s, r in zip(sc, R)]
    c = np.array([sum(z == g for z in v) for v, g, _ in rows], float)
    maj = (c > K / 2).astype(float)
    d = maj - c / K
    a = boot(d)
    bw = [boot(maj - np.array([v[j] == g for v, g, _ in rows], float)) for j in range(K)]
    wb = float(np.mean([t[2] - t[1] for t in bw]))
    gr = np.array([gy for _, _, gy in rows], float)
    cg = boot(maj - gr)
    ties = sum(len([k for k, n in Counter(v).items() if n == max(Counter(v).values())]) > 1 for v, _, _ in rows)
    modal_ok = np.array([modal_first(v) == g for v, g, _ in rows], float)
    # expected accuracy of a K-subset majority, averaged over all subsets of the nine draws (binary rule)
    kcurve = {}
    for kk in (1, 3, 5, 7, 9):
        acc = []
        for s, r in zip(sc, R):
            cor = [z == r["gold"] for z in s["pool"]]
            n9, c9 = len(cor), sum(cor)
            # P(majority of a uniformly chosen kk-subset is correct) from the hypergeometric count
            pm = sum(_comb(c9, j) * _comb(n9 - c9, kk - j) for j in range(kk // 2 + 1, kk + 1)) / _comb(n9, kk)
            acc.append(pm)
        kcurve[kk] = float(np.mean(acc))
    d9 = np.array([(sum(z == r["gold"] for z in s["pool"]) > 4.5) - sum(z == r["gold"] for z in s["pool"]) / 9
                   for s, r in zip(sc, R)], float)
    W4[m] = {"N": len(R), "subsets": dict(Counter(r["subset"] for r in R)), "swapped": int(sum(r["swap"] for r in R)),
             "sc_verdict_equals_modal_first5": first5_ok, "greedy": float(gr.mean()), "acc_k1": float((c / K).mean()),
             "acc_k5": float(maj.mean()), "gain5": a, "width_a": a[2] - a[1], "width_b": wb,
             "ratio_b": (wb / (a[2] - a[1])) ** 2, "maj_minus_greedy": cg,
             "pos": float(np.clip(d, 0, None).mean()), "neg": float(np.clip(-d, 0, None).mean()),
             "R_gold": float(((c > 0) & (c < K)).mean()), "pers": int((c == 0).sum()),
             "unan_wrong": int(sum(len(set(v)) == 1 and v[0] != g for v, g, _ in rows)),
             "tie_votes": int(sum(z == "tie" for v, _, _ in rows for z in v)), "modal_ties": int(ties),
             "acc_k5_modal_first": float(modal_ok.mean()), "kcurve": kcurve, "gain9": boot(d9),
             "early_calls": float(np.mean([3 if len(set(v[:3])) == 1 else 5 for v, _, _ in rows]))}
    w = W4[m]
    P(f"\n### {m}: N={w['N']} test instances {w['subsets']}; swapped order {w['swapped']}; "
      f"stored SC verdict = modal of first five draws in {first5_ok}/{w['N']}")
    P(f"- Greedy Single-CoT {w['greedy']:.3f}; expected K=1 {w['acc_k1']:.4f}; K=5 binary majority (first five draws) "
      f"{w['acc_k5']:.4f}; modal first-occurrence {w['acc_k5_modal_first']:.4f} (modal ties {w['modal_ties']})")
    P(f"- Delta_MV (K=5) {a[0]:+.4f} [{a[1]:+.3f}, {a[2]:+.3f}]; positive {w['pos']:.4f}, negative {w['neg']:.4f} "
      f"(offset {w['neg'] / w['pos']:.0%}); R_gold {w['R_gold']:.3f}; c_i=0 {w['pers']}; unanimous wrong {w['unan_wrong']}; "
      f"tie votes {w['tie_votes']}/{5 * w['N']}; early-stopping calls {w['early_calls']:.2f}")
    P(f"- Precision: within-pool width {w['width_a']:.3f}; majority minus one draw mean width {wb:.3f} (x{w['ratio_b']:.1f}); "
      f"majority minus greedy {cg[0]:+.3f} [{cg[1]:+.3f}, {cg[2]:+.3f}]")
    P("- Expected binary-majority accuracy over all K-subsets of the nine draws: " +
      ", ".join(f"K={kk} {v:.4f}" for kk, v in kcurve.items()) +
      f"; nine-draw Delta (K=9 vs one of nine) {w['gain9'][0]:+.4f} [{w['gain9'][1]:+.3f}, {w['gain9'][2]:+.3f}]")
J["W4"] = W4


def clean(o):
    if isinstance(o, dict):
        return {str(k): clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean(v) for v in o]
    if isinstance(o, np.ndarray):
        return [clean(v) for v in o.tolist()]
    if isinstance(o, (np.floating, np.integer, np.bool_)):
        return o.item()
    return o


open(OUT_MD, "w", encoding="utf-8").write("\n".join(L) + "\n")
json.dump(clean(J), open(OUT_JS, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print("\n".join(L))
